export function rowToObject(tabName, row = []) {
  const cols = SHEET_TABS[tabName];
  const obj = {};
  for (let i = 0; i < cols.length; i++) {
    const key = cols[i];
    const raw = row[i] !== undefined && row[i] !== null ? String(row[i]) : '';
    if (BOOLEAN_FIELDS.has(key)) {
      if (raw === '') {
        obj[key] = !FALSE_DEFAULT_BOOLEANS.has(key);
      } else {
        obj[key] = raw.toLowerCase() === 'true' || raw === '1';
      }
    } else if (NUMBER_FIELDS.has(key)) {
      const parsed = Number(raw);
      if (raw === '' || !Number.isFinite(parsed)) {
        if (key === 'latitude' || key === 'longitude') obj[key] = null;
        else if (key === 'sortOrder' || key === 'stepOrder' || key === 'targetMonth') obj[key] = 0;
        else if (key === 'weatherCooldownDays') obj[key] = 5;
        else obj[key] = 1;
      } else {
        obj[key] = parsed;
      }
    } else {
      obj[key] = raw;
    }
  }
  return obj;
}

export function objectToRow(tabName, obj = {}) {
  const cols = SHEET_TABS[tabName];
  return cols.map((key) => {
    const val = obj[key];
    if (val === undefined || val === null) return '';
    if (typeof val === 'boolean') return val ? 'true' : 'false';
    return String(val);
  });
}

export function hashPassword(password, salt = crypto.randomBytes(16).toString('hex')) {
  const derived = crypto.scryptSync(password, salt, 64).toString('hex');
  return `${salt}:${derived}`;
}

export function verifyPassword(password, storedHash) {
  if (!storedHash || !storedHash.includes(':')) return false;
  const [salt, key] = storedHash.split(':');
  const derived = crypto.scryptSync(password, salt, 64).toString('hex');
  const a = Buffer.from(key, 'hex');
  const b = Buffer.from(derived, 'hex');
  if (a.length !== b.length) return false;
  return crypto.timingSafeEqual(a, b);
}

export function hashApiKey(rawKey) {
  return crypto.createHash('sha256').update(rawKey).digest('hex');
}

export function makeId(prefix = 'id') {
  return `${prefix}_${crypto.randomBytes(6).toString('hex')}`;
}

function formatOffsetDate(offsetDays) {
  const d = new Date();
  d.setHours(12, 0, 0, 0);
  d.setDate(d.getDate() + offsetDays);
  const year = d.getFullYear();
  const month = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
}

